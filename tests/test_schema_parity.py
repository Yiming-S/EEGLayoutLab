"""Every request format in eeglayoutlab.schemas gives exactly Node's outcome (design 0001, decision 4).

For each variant generated by tests/schema_parity/generate.mjs, Python must parse it as JSON.parse does,
accept or reject it as the Node normalizer does, and write the same canonical bytes.
"""
import copy
import json
import math
import struct

import pytest

from schema_parity_support import CASES, CORPUS, FORMATS, body_text, case_id, needs_node, require

require('pydantic')

from eeglayoutlab.schemas import jsjson  # noqa: E402
from eeglayoutlab.schemas.design_evaluation import canonical_json  # noqa: E402
from eeglayoutlab.schemas.registry import REQUEST_FORMATS  # noqa: E402


def python_outcome(format_name, text):
    """(parsed, accepted, canonical) as the Python service sees a request text."""
    try:
        value = jsjson.parse(text)
    except ValueError:
        return False, False, None
    try:
        return True, True, jsjson.stringify(REQUEST_FORMATS[format_name].normalize(value))
    except ValueError:
        return True, False, None


class _Key(str):
    pass


def iterative_repr(value):
    """repr() without recursion, for values nested deeper than the recursion limit."""
    out, stack = [], [value]
    while stack:
        item = stack.pop()
        if isinstance(item, list):
            out.append(f'[{len(item)}')
            stack.extend(reversed(item))
        elif isinstance(item, dict):
            out.append(f'{{{len(item)}')
            for key, child in reversed(item.items()):
                stack += [child, _Key(key)]
        elif isinstance(item, _Key):
            out.append('key ' + repr(str(item)))
        else:
            out.append(repr(item))
    return ' '.join(out)


def _double(hex_bits):
    return struct.unpack('>d', bytes.fromhex(hex_bits))[0]


@needs_node
def test_every_format_has_a_node_generator():
    assert sorted(FORMATS) == sorted(REQUEST_FORMATS)


@needs_node
@pytest.mark.parametrize('case', CASES, ids=case_id)
def test_variant_parity(case):
    format_name, variant = case
    parsed, accepted, canonical = python_outcome(format_name, body_text(variant))
    assert (parsed, accepted) == (variant['parsed'], variant['accepted']), variant.get('error')
    assert canonical == variant['canonical']


@needs_node
@pytest.mark.parametrize('format_name', sorted(REQUEST_FORMATS))
def test_variants_cover_both_outcomes(format_name):
    variants = FORMATS[format_name]
    accepted = sum(variant['accepted'] for variant in variants)
    assert 0 < accepted < len(variants)


@needs_node
@pytest.mark.parametrize('format_name', sorted(REQUEST_FORMATS))
def test_option_lists_match_node(format_name):
    # The variants send every value of Node's lists (formats/*.mjs), so a value added on one side fails parity;
    # this names the list that differs. The Python schemas build their allowed values from the same lists.
    node = CORPUS['formats'][format_name].get('options', {})
    assert node == {key: list(values) for key, values in REQUEST_FORMATS[format_name].options.items()}


@needs_node
def test_design_variants_cover_every_option():
    names = {variant['name'].split('-')[0] for variant in FORMATS['design-evaluation']}
    assert {'spacing', 'noise', 'prior', 'robustness', 'head', 'scenario', 'combo', 'name', 'bytes', 'envelope', 'fixture'} <= names


@needs_node
def test_canonical_design_requests_normalize_to_themselves():
    for variant in FORMATS['design-evaluation']:
        if variant['accepted']:
            request = jsjson.stringify(json.loads(variant['canonical'])['request'])
            assert canonical_json(jsjson.parse(request)) == request


@needs_node
@pytest.mark.parametrize('case', CASES, ids=case_id)
def test_iterative_parser_matches_json_loads(case):
    # jsjson.parse falls back to _parse_iterative for nesting deeper than Python's recursion limit.
    text = body_text(case[1])
    try:
        expected = iterative_repr(jsjson.parse(text))
    except ValueError:
        expected = 'error'
    try:
        actual = iterative_repr(jsjson._parse_iterative(text))
    except ValueError:
        actual = 'error'
    assert actual == expected


def _as_parsed(value):
    """A json.loads value as jsjson.parse holds it: every number a double."""
    if isinstance(value, dict):
        return {key: _as_parsed(child) for key, child in value.items()}
    if isinstance(value, list):
        return [_as_parsed(child) for child in value]
    return jsjson.to_number(value) if jsjson.is_number(value) else value


def _no_constants(name):
    raise ValueError(name)


@needs_node
@pytest.mark.parametrize('case', [case for case in CASES if 'text' in case[1]], ids=case_id)
def test_python_values_normalize_like_parsed_json(case):
    # Command-line and notebook callers pass Python values, in which integers stay int. The schemas must give
    # Node's outcome for them too, and must not change the value they are given.
    format_name, variant = case
    try:
        value = json.loads(variant['text'], parse_constant=_no_constants)
        if iterative_repr(_as_parsed(value)) != iterative_repr(jsjson.parse(variant['text'])):
            return  # json.loads reads this text differently (a byte order mark, for example)
        before = copy.deepcopy(value)
    except (ValueError, RecursionError):
        return
    try:
        canonical = jsjson.stringify(REQUEST_FORMATS[format_name].normalize(value))
    except ValueError:
        canonical = None
    assert canonical == variant['canonical']
    assert iterative_repr(value) == iterative_repr(before)


def test_deep_nesting_is_parsed_like_json_parse():
    depth = 30000
    value = jsjson.parse('{"a":' + '[' * depth + '1' + ']' * depth + ',"a":2,"b":[{"c":-0}]}')
    assert value == {'a': 2.0, 'b': [{'c': 0.0}]} and list(value) == ['a', 'b']
    nested = jsjson.parse('[' * depth + ']' * depth)
    for _ in range(depth - 1):
        nested = nested[0]
    assert nested == []
    for text in ('[' * depth + ']' * (depth - 1), '[' * depth + ']' * depth + 'x', '[' * depth + 'NaN' + ']' * depth):
        with pytest.raises(ValueError):
            jsjson.parse(text)


@needs_node
def test_number_spelling_matches_json_stringify():
    mismatches = [(bits, text, jsjson.number_to_string(_double(bits))) for bits, text in CORPUS['numbers']
                  if jsjson.number_to_string(_double(bits)) != text]
    assert mismatches == []
    # Python's own spelling differs for many of the same values.
    assert sum(json.dumps(_double(bits)) != text for bits, text in CORPUS['numbers']) > len(CORPUS['numbers']) // 4


@needs_node
def test_hypot_matches_v8_bit_for_bit():
    rows = [([_double(b) for b in row[:3]], _double(row[3])) for row in CORPUS['hypot']]
    assert [d for d, expected in rows if struct.pack('>d', jsjson.hypot(*d)) != struct.pack('>d', expected)] == []
    # math.hypot differs from V8's Kahan sum in the last bit for some inputs.
    assert any(math.hypot(*d) != expected for d, expected in rows)


@needs_node
def test_significant_digit_and_rounding_rules_match():
    assert [b for b, expected in CORPUS['precision'] if jsjson.equals_to_precision(_double(b), 4) != expected] == []
    for b, expected, rounded in CORPUS['round2']:
        value = _double(b)
        assert jsjson.round_half_up(value * 100) == _double(rounded)
        assert (jsjson.round_half_up(value * 100) / 100 == value) == expected
    # Python's round() is half-even and so is not Math.round.
    assert round(0.5) != jsjson.round_half_up(0.5)


def test_utf16_slice_and_quote_follow_javascript():
    name = 'a' + '\U0001F600' * 60
    sliced = jsjson.slice_utf16(name, 100)
    assert len(sliced) == 51 and sliced[-1] == '\ud83d'  # 'a', 49 emoji, then the lone high surrogate of the 50th
    assert name[:100] != sliced
    assert jsjson.quote(sliced).endswith('\\ud83d"')
    assert jsjson.quote(' \x7f\x00\x1f"\\') == '" \x7f\\u0000\\u001f\\"\\\\"'
    with pytest.raises(ValueError):
        jsjson.parse('NaN')
    with pytest.raises(ValueError):
        jsjson.parse('﻿{}')
